package key

import "testing"

func TestKeyHashString(t *testing.T) {
	for _, kh := range []AbstractHash{
		Uint64(0x1234567890abcdef),
		Bytes16{0x12, 0x34, 0x56, 0x78, 0x90, 0xab, 0xcd, 0xef, 0x01, 0x23, 0x45, 0x67, 0x89, 0x0a, 0xbc, 0xde},
		Bytes32{0x12, 0x34, 0x56, 0x78, 0x90, 0xab, 0xcd, 0xef, 0x01, 0x23, 0x45, 0x67, 0x89, 0x0a, 0xbc, 0xde,
			0xfe, 0xdc, 0xba, 0x09, 0x87, 0x65, 0x43, 0x21, 0x10, 0x32, 0x54, 0x76, 0x98, 0xba, 0xdc, 0xfe},
	} {
		s := kh.String()
		var kh2 AbstractHashPtr
		switch kh.(type) {
		case Uint64:
			kh2 = new(Uint64)
		case Bytes16:
			kh2 = new(Bytes16)
		case Bytes32:
			kh2 = new(Bytes32)
		default:
			t.Fatalf("unknown KeyHash type: %T", kh)
		}
		err := kh2.SetFromString(s)
		if err != nil {
			t.Fatalf("SetFromString failed for %T with error: %v", kh, err)
		}
		s2 := kh2.String()
		if s != s2 {
			t.Fatalf("String mismatch for %T: expected %s but got %s", kh, s, s2)
		}
	}
}
